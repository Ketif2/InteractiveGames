// Funciones sin cambios
export const selectObjectsByDifficultyAndCategory = (difficulty, category = 'Todos') => {
    // Filtrar objetos por categoría si no es "Todos"
    let filteredObjects = [...memoryObjects]; // Hacer una copia para no modificar el original
    
    if (category !== 'Todos') {
        filteredObjects = memoryObjects.filter(obj => obj.category === category);
        
        // Verificar si hay suficientes objetos en la categoría
        if (filteredObjects.length < 10) {
            console.warn(`No hay suficientes objetos en la categoría ${category}. Usando todos los objetos.`);
            filteredObjects = [...memoryObjects];
        }
    }
    
    // Determine number of items based on difficulty
    // Fácil: 2 filas (10 elementos)
    // Medio: 3 filas (15 elementos)
    // Difícil: 4 filas (20 elementos)
    let count;
    switch(difficulty) {
        case 'fácil':
            count = 10; // 2 filas de 5 elementos
            break;
        case 'medio':
            count = 15; // 3 filas de 5 elementos
            break;
        case 'difícil':
        default:
            count = 20; // 4 filas de 5 elementos
            break;
    }
    
    // Función mejorada de Fisher-Yates shuffle para aleatorización más efectiva
    const shuffleArray = (array) => {
        const shuffled = [...array];
        for (let i = shuffled.length - 1; i > 0; i--) {
            const j = Math.floor(Math.random() * (i + 1));
            [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
        }
        return shuffled;
    };
    
    // Primero, mezclamos el array de objetos filtrados para añadir variabilidad
    const shuffledObjects = shuffleArray(filteredObjects);
    let selectedObjects = [];
    
    switch(difficulty) {
        case 'fácil':
            // Para dificultad fácil, necesitamos objetos con claras diferencias de peso
            // Introducimos variabilidad en el punto de inicio
            const randomStartEasy = Math.floor(Math.random() * Math.min(20, shuffledObjects.length / 4));
            
            // Creamos un conjunto de rangos separados para seleccionar objetos con clara diferencia
            const easyRanges = [];
            const totalRanges = Math.min(count, 5); // Máximo 5 rangos para 10 objetos (2 por rango)
            const rangeSize = Math.floor(shuffledObjects.length / totalRanges);
            
            for (let i = 0; i < totalRanges; i++) {
                const rangeStart = i * rangeSize;
                const rangeEnd = (i + 1) * rangeSize - 1;
                easyRanges.push([rangeStart, rangeEnd]);
            }
            
            // De cada rango, seleccionamos algunos objetos aleatoriamente
            const objectsPerRange = Math.ceil(count / totalRanges);
            
            for (const [start, end] of easyRanges) {
                // Mezclamos el rango para más aleatoriedad
                const rangeObjects = shuffleArray(shuffledObjects.slice(start, end + 1));
                // Tomamos algunos objetos de este rango
                const selected = rangeObjects.slice(0, objectsPerRange);
                selectedObjects = [...selectedObjects, ...selected];
                
                if (selectedObjects.length >= count) break;
            }
            
            // Aseguramos que tenemos exactamente la cantidad correcta
            selectedObjects = selectedObjects.slice(0, count);
            break;
            
        case 'medio':
            // Para dificultad media, tomamos objetos con diferencia moderada de peso
            // Introducimos variabilidad en el punto de inicio
            const randomStartPercentage = 15 + Math.floor(Math.random() * 20); // Entre 15% y 35%
            const randomStart = Math.floor(shuffledObjects.length * (randomStartPercentage / 100));
            
            // Tomamos un segmento más amplio pero no tan disperso como en fácil
            const segmentSizePercentage = 40 + Math.floor(Math.random() * 20); // Entre 40% y 60%
            const segmentSize = Math.floor(shuffledObjects.length * (segmentSizePercentage / 100));
            const segmentEnd = Math.min(randomStart + segmentSize, shuffledObjects.length);
            
            const mediumSegment = shuffledObjects.slice(randomStart, segmentEnd);
            
            // Dividimos el segmento en secciones para selección más variada
            const numSections = 3;
            const sectionSize = Math.floor(mediumSegment.length / numSections);
            
            for (let i = 0; i < numSections; i++) {
                const sectionStart = i * sectionSize;
                const sectionEnd = (i + 1) * sectionSize;
                const section = mediumSegment.slice(sectionStart, sectionEnd);
                
                // Seleccionamos objetos aleatoriamente de cada sección
                const objectsToSelectFromSection = Math.ceil(count / numSections);
                const sectionShuffled = shuffleArray(section);
                
                selectedObjects = [...selectedObjects, ...sectionShuffled.slice(0, objectsToSelectFromSection)];
            }
            
            // Nos aseguramos de tener la cantidad correcta
            selectedObjects = selectedObjects.slice(0, count);
            
            // Si no tenemos suficientes, completamos con objetos aleatorios
            if (selectedObjects.length < count) {
                const remainingObjects = shuffledObjects.filter(obj => 
                    !selectedObjects.some(selected => selected.id === obj.id)
                );
                
                const additionalObjects = shuffleArray(remainingObjects).slice(0, count - selectedObjects.length);
                selectedObjects = [...selectedObjects, ...additionalObjects];
            }
            break;
            
        case 'difícil':
            // Para dificultad difícil, necesitamos objetos con pesos muy similares
            // Variamos el punto de inicio para cada juego
            const difficultyRangeStart = 30 + Math.floor(Math.random() * 25); // Entre 30% y 55%
            const start = Math.floor(shuffledObjects.length * (difficultyRangeStart / 100));
            
            // El tamaño del segmento también varía para introducir aleatoriedad
            const difficultySegmentSize = 20 + Math.floor(Math.random() * 15); // Entre 20% y 35%
            const size = Math.floor(shuffledObjects.length * (difficultySegmentSize / 100));
            const end = Math.min(start + size, shuffledObjects.length);
            
            // Tomamos un segmento aleatorio pero contiguo para asegurar similitud de peso
            const difficultSegment = shuffledObjects.slice(start, end);
            
            // Para añadir variabilidad pero mantener la dificultad, seleccionamos de varias
            // sub-secciones contiguas dentro del segmento difícil
            const numSubsections = Math.min(3, Math.floor(difficultSegment.length / (count / 2)));
            const subsectionSize = Math.floor(difficultSegment.length / numSubsections);
            
            // Aleatorizamos qué subsecciones usar
            const subsectionIndices = Array.from({length: numSubsections}, (_, i) => i);
            const shuffledSubsectionIndices = shuffleArray(subsectionIndices);
            
            // Seleccionamos objetos de las subsecciones elegidas
            for (let i = 0; i < shuffledSubsectionIndices.length && selectedObjects.length < count; i++) {
                const idx = shuffledSubsectionIndices[i];
                const subsectionStart = idx * subsectionSize;
                const subsectionEnd = (idx + 1) * subsectionSize;
                
                const subsection = difficultSegment.slice(subsectionStart, subsectionEnd);
                const objectsToTake = Math.min(Math.ceil(count / numSubsections), count - selectedObjects.length);
                
                selectedObjects = [...selectedObjects, ...subsection.slice(0, objectsToTake)];
            }
            
            // Completamos si es necesario con objetos cercanos
            if (selectedObjects.length < count) {
                const remainingCount = count - selectedObjects.length;
                // Buscamos objetos cercanos a los ya seleccionados para mantener similitud
                const idsSelected = new Set(selectedObjects.map(obj => obj.id));
                
                // Priorizamos objetos con IDs cercanos a los ya seleccionados
                const averageId = Math.floor(selectedObjects.reduce((sum, obj) => sum + obj.id, 0) / selectedObjects.length);
                
                const similarObjects = shuffledObjects
                    .filter(obj => !idsSelected.has(obj.id))
                    .sort((a, b) => Math.abs(a.id - averageId) - Math.abs(b.id - averageId))
                    .slice(0, remainingCount);
                
                selectedObjects = [...selectedObjects, ...similarObjects];
            }
            break;
            
        default:
            // Por defecto, seleccionamos completamente al azar
            selectedObjects = shuffleArray(shuffledObjects).slice(0, count);
    }
    
    // Aseguramos que tenemos exactamente la cantidad correcta de objetos
    selectedObjects = selectedObjects.slice(0, count);
    
    // Mezcla final usando Fisher-Yates para la presentación
    return shuffleArray(selectedObjects);
};

// Mantener la función original para compatibilidad
export const selectObjectsByDifficulty = (difficulty) => {
    return selectObjectsByDifficultyAndCategory(difficulty, 'Todos');
};